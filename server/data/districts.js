export function buildDistricts() {
  return RAW.map((d) => ({
    ...d,
    sample: true,
    households: d.households.map(([surname, members, zone], i) => ({
      id: `${d.id}-hh-${String(i + 1).padStart(2, '0')}`,
      label: `${surname} household`,
      members,
      zone,
      sample: true,
    })),
  }));
}

